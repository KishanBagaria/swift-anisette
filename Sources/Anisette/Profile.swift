import Foundation

struct Profile: Sendable {
    struct Segment: Sendable { let address: UInt64; let size: UInt64; let offset: Int; let length: Int }
    struct Image: Sendable {
        let name: String
        let segments: [Segment]
        let data: Data

        func load(into engine: Unicorn) throws {
            let data = data
            var pages: [Range<UInt64>] = []
            for segment in segments where segment.size != 0 {
                try require(segment.size <= 1 << 30 && segment.address <= UInt64.max - segment.size,
                            "Invalid image segment")
                let start = segment.address & ~UInt64(4095)
                let end = try guestAligned(segment.address + segment.size, to: 4096)
                pages.append(start..<end)
            }
            var merged: [Range<UInt64>] = []
            for page in pages.sorted(by: { $0.lowerBound < $1.lowerBound }) {
                if let last = merged.last, page.lowerBound <= last.upperBound {
                    merged[merged.count - 1] = last.lowerBound..<max(last.upperBound, page.upperBound)
                } else { merged.append(page) }
            }
            for page in merged { try engine.map(page.lowerBound, page.upperBound - page.lowerBound) }
            for segment in segments where segment.length > 0 {
                try require(segment.offset >= 0 && segment.length <= data.count
                    && segment.offset <= data.count - segment.length && UInt64(segment.length) <= segment.size,
                            "Image segment exceeds file")
                try engine.write(segment.address, data[segment.offset..<segment.offset + segment.length])
            }
        }

        static func withoutPointerAuthentication(_ value: UInt32) -> UInt32 {
            switch value & 0xfffffc00 {
            case 0xd71f0800, 0xd71f0c00, 0xd61f0800, 0xd61f0c00: return 0xd61f0000 | (value & 0x3e0)
            case 0xd73f0800, 0xd73f0c00, 0xd63f0800, 0xd63f0c00: return 0xd63f0000 | (value & 0x3e0)
            case 0xdac10000, 0xdac10400, 0xdac10800, 0xdac10c00,
                 0xdac11000, 0xdac11400, 0xdac11800, 0xdac11c00: return 0xd503201f
            default: break
            }
            switch value {
            case 0xd65f0bff, 0xd65f0fff: return 0xd65f03c0
            case 0xd503211f, 0xd503215f, 0xd503219f, 0xd50321df,
                 0xd503233f, 0xd503237f, 0xd50323bf, 0xd50323ff, 0xd50320ff: return 0xd503201f
            default: break
            }
            switch value & 0xffffffe0 {
            case 0xdac123e0, 0xdac127e0, 0xdac12be0, 0xdac12fe0, 0xdac133e0,
                 0xdac137e0, 0xdac13be0, 0xdac13fe0, 0xdac143e0, 0xdac147e0: return 0xd503201f
            default: return value
            }
        }
    }
    /// Absolute guest addresses that ADIRuntime calls or checks in these images.
    struct Entries: Codable, Sendable, Equatable {
        let startProvisioning: UInt64
        let endProvisioning: UInt64
        let requestOTP: UInt64
        let daemonMain: UInt64
        let fairPlayDaemonMain: UInt64
        let kernelStart: UInt64
        let kernelSetup: UInt64
        let kernelInit: UInt64
        let kernelMessage: UInt64
        let kernelStackProbe: UInt64
        let kernelStackProbeValue: UInt64
    }
    let system: AnisetteSystemInfo
    let images: [Image]
    let entries: Entries
    let imports: [String: UInt64]
    let exports: [String: UInt64]
    /// Guest address of each prelinked shared-cache function stub, mapped to its resolved target.
    let functions: [UInt64: UInt64]
    /// Guest address of each prelinked shared-cache pointer slot, mapped to its resolved target.
    let slots: [UInt64: UInt64]
    let icxs: Data

    /// The contents of `Resources/Profile.json`, generated by `make rotate`.
    struct Configuration: Codable, Sendable {
        var build: PinnedBuild
        let system: AnisetteSystemInfo
        let entries: Entries
        let functions: [String: String]
        let slots: [String: String]

        private static let bundled = Result {
            guard let url = Bundle.module.url(forResource: "Profile", withExtension: "json") else {
                throw AnisetteError("Missing ADI configuration")
            }
            return try JSONDecoder().decode(Self.self, from: Data(contentsOf: url))
        }

        static func load() throws -> Self { try bundled.get() }
    }

    /// Guest load region of each image, in load order.
    static let bases: [(name: String, address: UInt64)] = [
        ("CoreFP", 0x100000000000), ("AppleMediaServices", 0), ("commerce", 0x1000c0000000),
        ("adid", 0x200000000000), ("fairplayd", 0x600000000000), ("FairPlayIOKit", 0x700000000000),
    ]

    /// Guest address `image` loads at. AppleMediaServices stays at its shared-cache address, where
    /// its prelinked pointers already point. FairPlayIOKit keeps the page offset of its `__TEXT`
    /// address, which varies by build, so ADRP references retain the slide of its data segments.
    static func base(of name: String, image: MachO) throws -> UInt64 {
        guard let address = bases.first(where: { $0.name == name })?.address else {
            throw AnisetteError("No guest base for \(name)")
        }
        switch name {
        case "AppleMediaServices": return image.base
        case "FairPlayIOKit": return address | image.base & 4095
        default: return address
        }
    }

    static func load(assets: [String: Data], configuration: Configuration? = nil) throws -> Profile {
        let configuration = try configuration ?? Configuration.load()
        var originals: [String: MachO] = [:]
        for name in ["CoreFP", "AppleMediaServices", "commerce", "adid", "fairplayd", "FairPlayIOKit"] {
            guard let bytes = assets[name] else { throw AnisetteError("Missing Apple image \(name)") }
            originals[name] = try MachO(bytes)
        }
        var exports: [String: UInt64] = [:]
        for (imageName, base, names) in [
            ("CoreFP", UInt64(0x100000000000),
             ["_WIn9UJ86JKdV4dM", "_X46O5IeS", "_YlCJ3lg", "_dku592fbFAj", "_fdjkDSAFjklaf2s", "_lxpgvVMLd0S7uRl"]),
            ("AppleMediaServices", originals["AppleMediaServices"]!.base,
             ["_cp2g1b9ro", "_Mib5yocT", "_Fc3vhtJDvr", "_IPaI1oem5iL", "_jEHf8Xzsv8K"]),
        ] {
            let image = originals[imageName]!
            let symbols = try image.exports()
            for name in names {
                guard let value = symbols[name], value >= image.base else { throw AnisetteError("Missing Apple export \(name)") }
                exports[name] = try guestAddress(base, offset: value - image.base)
            }
        }
        var imports: [String: UInt64] = [:]
        func resolve(_ name: String) throws -> UInt64 {
            if let value = exports[name] ?? imports[name] { return value }
            try require(imports.count < 0x7000, "Too many guest imports")
            let value = GuestServices.base + UInt64(imports.count * 16)
            imports[name] = value
            return value
        }
        func resolveTable(_ table: [String: String]) throws -> [UInt64: UInt64] {
            let entries = try table.map { key, name -> (UInt64, String) in
                guard let address = UInt64(key) else { throw AnisetteError("Invalid shared-cache symbol") }
                return (address, name)
            }
            var resolved: [UInt64: UInt64] = [:]
            for (address, name) in entries.sorted(by: { $0.0 < $1.0 }) { resolved[address] = try resolve(name) }
            return resolved
        }
        let functions = try resolveTable(configuration.functions)
        let slots = try resolveTable(configuration.slots)
        var images: [Image] = []
        for (name, _) in bases {
            var image = originals[name]!
            let base = try Self.base(of: name, image: image)
            if name == "AppleMediaServices" { try image.prelink(functions) } else {
                try image.relocate(to: base, resolve: resolve)
            }
            if name == "FairPlayIOKit" {
                try image.relocateKernel(to: base, kernelBase: configuration.build.kernelCollectionBase, resolve: resolve)
            }
            for section in image.sections where section.flags & 0x80000400 != 0 {
                try image.data.checkRange(section.offset, section.size)
                image.data.withUnsafeMutableBytes { bytes in
                    let section = UnsafeMutableRawBufferPointer(rebasing: bytes[section.offset..<section.offset + section.size])
                    for offset in stride(from: 0, to: section.count - 3, by: 4) {
                        let instruction = UInt32(littleEndian: section.loadUnaligned(fromByteOffset: offset, as: UInt32.self))
                        let stripped = Image.withoutPointerAuthentication(instruction)
                        guard stripped != instruction else { continue }
                        section.storeBytes(of: stripped.littleEndian, toByteOffset: offset, as: UInt32.self)
                    }
                }
            }
            let segments = try image.segments.filter { $0.name != "__PAGEZERO" }.map { segment in
                try require(segment.address >= image.base, "Segment precedes image base")
                return Segment(address: try guestAddress(base, offset: segment.address - image.base), size: segment.size,
                               offset: segment.offset, length: segment.length)
            }
            images.append(Image(name: name, segments: segments, data: image.data))
        }
        guard let icxs = assets["CoreFP.icxs"] else { throw AnisetteError("Missing Apple image CoreFP.icxs") }
        return Profile(system: configuration.system, images: images, entries: configuration.entries,
                       imports: imports, exports: exports, functions: functions, slots: slots, icxs: icxs)
    }
}
